import sharp from "sharp";
import { createHash } from "node:crypto";
import { mkdir, readFile, stat, writeFile } from "node:fs/promises";
import path from "node:path";

// Originals are read-only. Keep their order and full aspect ratio; CSS keeps
// the existing crops, including the hero's object-position.
const photos = [
  { name: "hero", source: "제목_없는_디자인_1767953447116.png", widths: [480, 768, 1024, 1299] },
  { name: "profile", source: "김민주_프로필_240525_1765811099605.png", widths: [320, 640, 960] },
  { name: "slide1", source: "3_1767890854722.jpg", widths: [300, 600, 900] },
  { name: "slide2", source: "GTJ01322_1767890854737.jpg", widths: [300, 600, 900] },
  { name: "slide3", source: "KakaoTalk_20250523_104833739_03_1767890854743.jpg", widths: [300, 600, 900] },
  { name: "slide4", source: "KakaoTalk_20250523_104936309_01_1767890854746.jpg", widths: [300, 600, 900] },
  { name: "slide5", source: "KakaoTalk_20250523_104936309_02_1767890854749.jpg", widths: [300, 600, 900] },
  { name: "slide6", source: "KakaoTalk_20250523_104936309_03_1767890854752.jpg", widths: [300, 600, 900] },
  { name: "slide7", source: "KakaoTalk_20251210_233230339_1767890854755.jpg", widths: [300, 600, 900] },
  { name: "slide8", source: "M4J01775_1767890854762.jpg", widths: [300, 600, 900] },
  { name: "slide9", source: "M4J01778_1767890854765.jpg", widths: [300, 600, 900] },
];

const outputDir = "client/src/assets/home";
await mkdir(outputDir, { recursive: true });
await mkdir("reports", { recursive: true });
const imports: string[] = [];
const definitions: string[] = [];
const report = [];
for (const photo of photos) {
  const source = path.join("attached_assets", photo.source);
  const original = await readFile(source);
  const hash = createHash("sha256").update(original).digest("hex");
  const metadata = await sharp(original).metadata();
  const variants = [];
  for (const width of photo.widths) {
    const filename = `${photo.name}-${width}.webp`;
    const file = path.join(outputDir, filename);
    const result = await sharp(original)
      .rotate()
      .resize({ width, withoutEnlargement: true })
      .webp({ quality: 85, effort: 6 })
      .toFile(file);
    const identifier = `${photo.name}${width}`;
    imports.push(`import ${identifier} from "./${filename}";`);
    variants.push({ file, width: result.width, height: result.height, bytes: (await stat(file)).size, identifier });
  }
  // 2x fallback for browsers that do not select srcSet.
  const fallback = variants[1];
  definitions.push(`export const ${photo.name} = {
  src: ${fallback.identifier},
  srcSet: [${variants.map((v) => `\`\${${v.identifier}} ${v.width}w\``).join(", ")}].join(", "),
  width: ${fallback.width},
  height: ${fallback.height},
};`);
  if (hash !== createHash("sha256").update(await readFile(source)).digest("hex")) {
    throw new Error(`Original changed during optimization: ${source}`);
  }
  report.push({
    name: photo.name, source, originalBytes: original.length,
    originalWidth: metadata.width, originalHeight: metadata.height,
    originalSha256: hash,
    variants: variants.map(({ identifier, ...variant }) => variant),
  });
}
await writeFile(path.join(outputDir, "images.ts"),
  "// Generated by npm run images:optimize. Do not edit by hand.\n" +
  imports.join("\n") + "\n\n" + definitions.join("\n\n") + "\n\n" +
  "export const activityImages = [slide1, slide2, slide3, slide4, slide5, slide6, slide7, slide8, slide9];\n");
await writeFile("reports/home-image-assets.json", JSON.stringify(report, null, 2) + "\n");
console.log(`Generated responsive WebP variants for ${report.length} photos; originals preserved.`);
